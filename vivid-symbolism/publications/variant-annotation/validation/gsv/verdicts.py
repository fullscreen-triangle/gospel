SYN = Witness(A_c=[EX.SequencingAssay, EX.Genotyping], U_c=[EX.Sequencer, EX.BiologicalSample],
              A_d=[EX.ImputationActivity, EX.VariantPrediction], U_d=[EX.ReferencePanel, EX.Model],
              G_d=[PROV.SoftwareAgent])
ACTS = [EX.SequencingAssay, EX.Genotyping, EX.ImputationActivity, EX.VariantPrediction,
        PROV.Activity, EX.Alignment]
INPUTS = [EX.Sequencer, EX.BiologicalSample, EX.ReferencePanel, EX.Model, PROV.Entity]
AGENTS = [PROV.Person, PROV.SoftwareAgent, PROV.Organization]


def random_provenance(rng, n_records=8):
    """A list of triples (to be added in any order) over records with
    generation chains through records used by later activities."""
    T = []
    recs = [ind(f"rec{k}") for k in range(n_records)]
    for r in recs:
        T.append((r, RDF.type, EX.GenomicRecord))
    k = 0
    for i, r in enumerate(recs):
        if rng.random() < 0.15:
            continue                        # no recorded generation: a symbol
        a = ind(f"act{k}"); k += 1
        T.append((r, GEN, a))
        if rng.random() < 0.8:
            T.append((a, RDF.type, ACTS[rng.integers(len(ACTS))]))
        if rng.random() < 0.5:
            u = ind(f"in{k}")
            T += [(a, USED, u), (u, RDF.type, INPUTS[rng.integers(len(INPUTS))])]
        if i > 0 and rng.random() < 0.45:
            T.append((a, USED, recs[rng.integers(i)]))       # chain to an earlier record
        if rng.random() < 0.35:
            x = ind(f"ag{k}")
            T += [(a, ASSOC, x), (x, RDF.type, AGENTS[rng.integers(len(AGENTS))])]
    return recs, T


def graph_of(triples) -> Graph:
    g = Graph()
    for t in triples:
        g.add(t)
    return g


def verdict_of(gr):
    return verdict(*gr)
